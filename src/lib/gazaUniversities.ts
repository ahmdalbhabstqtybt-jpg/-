export const GAZA_UNIVERSITY_NAMES: string[] = GAZA_INSTITUTIONS.map((inst) => inst.name);

export function getDeanshipsForInstitution(institutionName: string): GazaDeanship[] {
  const found = GAZA_INSTITUTIONS.find((inst) => inst.name === institutionName);
  return found ? found.deanships : [];
}

export function getDepartmentsForDeanship(
  institutionName: string,
  deanshipName: string,
): string[] {
  const deanships = getDeanshipsForInstitution(institutionName);
  const found = deanships.find((d) => d.name === deanshipName);
  return found ? found.departments : [];
}

export function getAllGazaDepartments(): {
  university: string;
  category: GazaInstitutionCategory;
  faculty: string;
  department: string;
}[] {
  const list: {
    university: string;
    category: GazaInstitutionCategory;
    faculty: string;
    department: string;
  }[] = [];
  for (const inst of GAZA_INSTITUTIONS) {
    for (const dean of inst.deanships) {
      for (const dept of dean.departments) {
        list.push({
          university: inst.name,
          category: inst.category,
          faculty: dean.name,
          department: dept,
        });
      }
    }
  }
  return list;
}

export function inferMajorFromGaza(faculty?: string, department?: string): import('../types/dirasati').MajorId {
  const text = `${faculty || ''} ${department || ''}`;
  if (/صيدل/.test(text)) return 'pharmacy';
  if (/حقوق|قانون|شريعة|شرط|أمني|جنائي|قضائ/.test(text)) return 'law';
  if (/فنون|جرافيك|ديكور|خزف|نحت|تصميم داخلي/.test(text)) return 'arts';
  if (/رياضي|بدنية|ألعاب/.test(text)) return 'sports';
  if (/إعلام|صحافة|إذاعة|تلفزيون|علاقات عامة|اتصال|ترجمة|لغات/.test(text)) return 'media';
  if (/تربي|مناهج|نفس|إرشاد|تعليم/.test(text)) return 'education';
  if (/اجتماع|إنساني|تاريخ|إسلام|عربية|أسري/.test(text)) return 'humanities';
  if (/رياضيات|فيزياء|كيمياء(?! صيد)|أحياء|جيولوجيا|بيئة|علوم(?! الحاسوب| إدارية| مالية| طبية| أمنية| شرط)/.test(text)) {
    return 'sciences';
  }
  if (/طب|تمريض|قبالة|أسنان|مختبر|علاج طبيعي|أشعة|تخدير|صحية|طبية/.test(text)) return 'medicine';
  if (/حاسوب|برمجي|تكنولوجيا المعلومات|بيانات|شبكات|أمن المعلومات|وسائط|ويب|سحابي/.test(text)) return 'it';
  if (/هندس|ميكاترونكس|عمارة|عمراني|سيارات|طاقة|ميكانيك|أتمتة|تبريد|مساحة/.test(text)) return 'engineering';
  if (/إدار|محاسب|اقتصاد|مالي|مصرف|تسويق|أعمال|تجارة|مشاريع/.test(text)) return 'business';
  return 'engineering';
}
